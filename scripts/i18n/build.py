#!/usr/bin/env python3
"""Validate authored translations and regenerate embedded Web/Slint assets."""
import argparse
import ast
import html
from collections import Counter
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
LANGUAGES = ('zh-Hans', 'zh-Hant', 'en', 'ja', 'ko')
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='fail on stale generated assets')
args = parser.parse_args()

def placeholders(text):
    return Counter(re.findall(r'\{\d+\}', text))

def read(name):
    data = json.loads((ROOT / 'locales' / (name + '.json')).read_text())
    for source, values in data.items():
        if re.fullmatch(r'(?:Bearer|Basic)\s+\{\d+\}', source):
            raise SystemExit(f'{name}: HTTP authorization must not be translated: {source!r}')
        for language in LANGUAGES:
            value = values.get(language)
            if not isinstance(value, str) or not value:
                raise SystemExit(f'{name}: missing {language}: {source!r}')
            if any(mark in value for mark in ('⁇', '�', '<unk>', '??')):
                raise SystemExit(f'{name}: invalid text {language}: {source!r}')
            if placeholders(source) != placeholders(value):
                raise SystemExit(f'{name}: placeholder mismatch {language}: {source!r}')
    return data

def output(path, content):
    path = ROOT / path
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f'Stale translation asset: {path.relative_to(ROOT)}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)

web = read('web')
screen = read('screen')
# Keep authored call sites and catalogs in sync without parsing live device data.
for path in (ROOT / 'zte-agent/ui').glob('*.js'):
    if path.name == 'locales.js':
        continue
    for literal in re.findall(r'''\b(?:tr|t)\(\s*("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')''', path.read_text()):
        if ast.literal_eval(literal) not in web:
            raise SystemExit(f'Missing Web translation in {path.name}: {literal}')
for path in (ROOT / 'zte-agent/ui').glob('*.html'):
    for literal in re.findall(r'data-i18n(?:-[\w-]+)?="([^"]+)"', path.read_text()):
        if html.unescape(literal) not in web:
            raise SystemExit(f'Missing HTML translation in {path.name}: {literal}')
for path in (ROOT / 'u60-screen/src').rglob('*.rs'):
    if path.name == 'i18n.rs':
        continue
    for literal in re.findall(r'''i18n::(?:tr|format)\(\s*("(?:[^"\\]|\\.)*")''', path.read_text()):
        if json.loads(literal) not in screen:
            raise SystemExit(f'Missing screen translation in {path.name}: {literal}')
# Preview metadata is authored copy too. Validate nested labels, rows and guides.
def check_preview(value):
    if isinstance(value, str) and re.search(r'[\u3400-\u9fff]', value) and value not in screen:
        raise SystemExit('Missing preview translation: ' + value)
    if isinstance(value, list):
        for child in value:
            check_preview(child)
    if isinstance(value, dict):
        for key, child in value.items():
            if key not in ('id', 'root', 'group', 'type', 'tone', 'method', 'endpoint'):
                check_preview(child)
check_preview(json.loads((ROOT / 'u60-screen/assets/catalog.json').read_text()))
output('zte-agent/ui/locales.js', "// Generated by scripts/i18n/build.py; edit locales/web.json.\n'use strict';\nglobalThis.OpenU60Locales = " + json.dumps(web, ensure_ascii=False, separators=(',', ':')) + ';\n')
slint_keys = set()
for path in (ROOT / 'u60-screen/ui').glob('*.slint'):
    for key in re.findall(r'@tr\(\s*("(?:[^"\\]|\\.)*")\s*[,)]', path.read_text()):
        slint_keys.add(json.loads(key))
for language in LANGUAGES:
    header = 'Content-Type: text/plain; charset=UTF-8\nLanguage: ' + language + '\nPlural-Forms: nplurals=1; plural=0;\n'
    lines = ['# Generated from locales/screen.json; do not edit.', 'msgid ""', 'msgstr ' + json.dumps(header), '']
    for source in sorted(slint_keys):
        if source not in screen:
            raise SystemExit('Missing Slint translation: ' + source)
        lines += ['msgid ' + json.dumps(source, ensure_ascii=False), 'msgstr ' + json.dumps(screen[source][language], ensure_ascii=False), '']
    output('u60-screen/translations/' + language + '/LC_MESSAGES/u60-screen.po', '\n'.join(lines))
print(f'{len(web)} Web and {len(screen)} screen messages; {len(LANGUAGES)} complete locales; assets current')
